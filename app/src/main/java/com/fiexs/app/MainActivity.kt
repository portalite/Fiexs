class MainActivity : ComponentActivity() {

    private var generator: FiexsGenerator? = null

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)

        setContent {
            FiexsApp(
                generateImage = { prompt ->
                    withContext(Dispatchers.IO) {
                        if (generator == null) {
                            generator = FiexsGenerator(applicationContext)
                        }

                        generator!!.generate(prompt)
                    }
                }
            )
        }
    }

    override fun onDestroy() {
        generator?.close()
        generator = null
        super.onDestroy()
    }
}

private val Background = Color(0xFF101114)
private val SurfaceColor = Color(0xFF1B1A20)
private val Accent = Color(0xFFB69CFF)
private val TextColor = Color(0xFFF4F1F8)
private val Muted = Color(0xFF9995A3)

@Composable
fun FiexsApp(
    generateImage: suspend (String) -> List<Color>
) {
    var prompt by remember { mutableStateOf("") }
    var progress by remember { mutableIntStateOf(0) }
    var isGenerating by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf(false) }
    var error by remember { mutableStateOf("") }

    val gridSize = 32

    var pixels by remember {
        mutableStateOf(
            List(gridSize * gridSize) { Background }
        )
    }

    val scope = rememberCoroutineScope()

    MaterialTheme {
        Surface(
            modifier = Modifier.fillMaxSize(),
            color = Background
        ) {
            Column(
                modifier = Modifier
                    .fillMaxSize()
                    .padding(22.dp),
                horizontalAlignment = Alignment.CenterHorizontally
            ) {
                Spacer(modifier = Modifier.height(24.dp))

                Text(
                    text = "FIEXS",
                    fontSize = 34.sp,
                    fontWeight = FontWeight.Black,
                    color = TextColor
                )

                Spacer(modifier = Modifier.height(6.dp))

                Text(
                    text = "PIXEL INTELLIGENCE",
                    fontSize = 11.sp,
                    letterSpacing = 3.sp,
                    color = Accent
                )

                Spacer(modifier = Modifier.height(36.dp))

                Text(
                    text = "Create something.",
                    fontSize = 25.sp,
                    fontWeight = FontWeight.Bold,
                    color = TextColor
                )

                Spacer(modifier = Modifier.height(8.dp))

                Text(
                    text = "Turn your imagination into pixels.",
                    color = Muted,
                    fontSize = 14.sp
                )

                Spacer(modifier = Modifier.height(26.dp))

                OutlinedTextField(
                    value = prompt,
                    onValueChange = { prompt = it },
                    modifier = Modifier.fillMaxWidth(),
                    label = {
                        Text("What do you want to create?")
                    },
                    placeholder = {
                        Text("A cat, a dog, a ship...")
                    },
                    shape = RoundedCornerShape(16.dp),
                    colors = OutlinedTextFieldDefaults.colors(
                        focusedTextColor = TextColor,
                        unfocusedTextColor = TextColor,
                        focusedBorderColor = Accent,
                        unfocusedBorderColor = Color.DarkGray,
                        focusedLabelColor = Accent,
                        cursorColor = Accent
                    ),
                    singleLine = true
                )

                Spacer(modifier = Modifier.height(18.dp))

                Button(
                    onClick = {
                        if (prompt.isBlank()) return@Button

                        scope.launch {
                            isGenerating = true
                            generated = false
                            error = ""
                            progress = 0

                            try {
                                val result = generateImage(prompt)

                                pixels = result
                                progress = 100
                                generated = true
                            } catch (e: Exception) {
                                error = e.message ?: "Unknown error"
                            } finally {
                                isGenerating = false
                            }
                        }
                    },
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(54.dp),
                    enabled = prompt.isNotBlank() && !isGenerating,
                    shape = RoundedCornerShape(16.dp),
                    colors = ButtonDefaults.buttonColors(
                        containerColor = Accent,
                        contentColor = Color.Black
                    )
                ) {
                    Text(
                        text = if (isGenerating)
                            "Generating..."
                        else
                            "Generate",
                        fontWeight = FontWeight.Bold
                    )
                }

                Spacer(modifier = Modifier.height(28.dp))

                Box(
                    modifier = Modifier
                        .fillMaxWidth()
                        .aspectRatio(1f)
                        .background(
                            SurfaceColor,
                            RoundedCornerShape(20.dp)
                        )
                        .padding(16.dp),
                    contentAlignment = Alignment.Center
                ) {
                    Canvas(
                        modifier = Modifier.fillMaxSize()
                    ) {
                        val cellWidth = size.width / gridSize
                        val cellHeight = size.height / gridSize

                        for (y in 0 until gridSize) {
                            for (x in 0 until gridSize) {
                                val index = y * gridSize + x

                                drawRect(
                                    color = pixels[index],
                                    topLeft = Offset(
                                        x * cellWidth,
                                        y * cellHeight
                                    ),
                                    size = androidx.compose.ui.geometry.Size(
                                        cellWidth,
                                        cellHeight
                                    )
                                )
                            }
                        }
                    }
                }

                Spacer(modifier = Modifier.height(20.dp))

                if (isGenerating || generated) {
                    Text(
                        text = if (isGenerating)
                            "Generating with Fiexs AI..."
                        else
                            "Generation complete",
                        color = Accent,
                        fontSize = 14.sp
                    )

                    Spacer(modifier = Modifier.height(12.dp))

                    LinearProgressIndicator(
                        progress = { progress / 100f },
                        modifier = Modifier.fillMaxWidth(),
                        color = Accent,
                        trackColor = SurfaceColor
                    )
                }

                if (error.isNotBlank()) {
                    Spacer(modifier = Modifier.height(12.dp))

                    Text(
                        text = error,
                        color = Color(0xFFFF7777),
                        fontSize = 12.sp
                    )
                }

                Spacer(modifier = Modifier.weight(1f))

                Text(
                    text = "FIEXS • OFFLINE PIXEL ENGINE",
                    color = Muted,
                    fontSize = 10.sp,
                    letterSpacing = 1.5.sp
                )

                Spacer(modifier = Modifier.height(12.dp))
            }
        }
    }
}

private class FiexsGenerator(
    private val context: android.content.Context
) {
    private val environment = OrtEnvironment.getEnvironment()
    private var session: OrtSession? = null

    private fun loadModel(): OrtSession {
        if (session == null) {
            val modelBytes = context.assets
                .open("fiexs_pixel_1.onnx")
                .use { it.readBytes() }

            val options = OrtSession.SessionOptions()

            try {
                session = environment.createSession(
                    modelBytes,
                    options
                )
            } finally {
                options.close()
            }
        }

        return session!!
    }

    private fun classifyPrompt(prompt: String): Int {
        val text = prompt.lowercase(Locale.ROOT)

        return when {
            "uçak" in text || "airplane" in text -> 0
            "araba" in text || "otomobil" in text ||
                "car" in text -> 1
            "kuş" in text || "kus" in text ||
                "bird" in text -> 2
            "kedi" in text || "cat" in text -> 3
            "geyik" in text || "deer" in text -> 4
            "köpek" in text || "kopek" in text ||
                "dog" in text -> 5
            "kurbağa" in text || "kurbaga" in text ||
                "frog" in text -> 6
            "at" == text.trim() || "horse" in text -> 7
            "gemi" in text || "deniz" in text ||
                "ship" in text -> 8
            "kamyon" in text || "truck" in text -> 9
            else -> throw IllegalArgumentException(
                "Şimdilik kedi, köpek, kuş, geyik, " +
                "kurbağa, at, uçak, araba, gemi veya kamyon deneyin."
            )
        }
    }

    fun generate(prompt: String): List<Color> {
        val modelSession = loadModel()
        val label = classifyPrompt(prompt)

        val random = Random.Default

        val totalPixels = 3 * 32 * 32
        var image = FloatArray(totalPixels) {
            random.nextGaussian().toFloat()
        }

        val timesteps = 1000
        val steps = 100

        val betas = FloatArray(timesteps) { i ->
            0.0001f + (0.02f - 0.0001f) *
                i / (timesteps - 1)
        }

        val alphaBars = FloatArray(timesteps)
        var product = 1f

        for (i in 0 until timesteps) {
            product *= (1f - betas[i])
            alphaBars[i] = product
        }

        for (step in (steps - 1) downTo 0) {
            val t = step * (timesteps - 1) / (steps - 1)

            val previousT = if (step > 0) {
                (step - 1) * (timesteps - 1) / (steps - 1)
            } else {
                -1
            }

            val imageTensor = OnnxTensor.createTensor(
                environment,
                FloatBuffer.wrap(image),
                longArrayOf(1, 3, 32, 32)
            )

            val timeTensor = OnnxTensor.createTensor(
                environment,
                LongBuffer.wrap(longArrayOf(t.toLong())),
                longArrayOf(1)
            )

            val labelTensor = OnnxTensor.createTensor(
                environment,
                LongBuffer.wrap(longArrayOf(label.toLong())),
                longArrayOf(1)
            )

            val inputs = mapOf(
                "image" to imageTensor,
                "timestep" to timeTensor,
                "label" to labelTensor
            )

            val predictedNoise = try {
                modelSession.run(inputs).use { result ->
                    val output = result[0] as OnnxTensor
                    val buffer = output.floatBuffer

                    FloatArray(totalPixels).also {
                        buffer.get(it)
                    }
                }
            } finally {
                imageTensor.close()
                timeTensor.close()
                labelTensor.close()
            }

            val alphaBar = alphaBars[t]
            val previousAlphaBar = if (previousT >= 0) {
                alphaBars[previousT]
            } else {
                1f
            }

            val sqrtAlphaBar = sqrt(alphaBar)
            val sqrtOneMinusAlphaBar = sqrt(1f - alphaBar)

            val sqrtPrevious = sqrt(previousAlphaBar)
            val sqrtPreviousNoise = sqrt(1f - previousAlphaBar)

            val previousImage = FloatArray(totalPixels)

            for (i in 0 until totalPixels) {
                val predictedOriginal =
                    (image[i] -
                        sqrtOneMinusAlphaBar * predictedNoise[i]) /
                        sqrtAlphaBar

                previousImage[i] =
                    sqrtPrevious * predictedOriginal +
                    sqrtPreviousNoise * predictedNoise[i]
            }

            image = previousImage
        }

        val colors = ArrayList<Color>(32 * 32)

        for (pixel in 0 until 32 * 32) {
            val r = ((image[pixel].coerceIn(-1f, 1f) + 1f) / 2f)
            val g = ((image[1024 + pixel].coerceIn(-1f, 1f) + 1f) / 2f)
            val b = ((image[2048 + pixel].coerceIn(-1f, 1f) + 1f) / 2f)

            colors.add(Color(r, g, b))
        }

        return colors
    }

    fun close() {
        session?.close()
        session = null
    }
}

private fun Random.nextGaussian(): Double {
    var u1 = nextDouble()
    val u2 = nextDouble()

    if (u1 < 1e-10) {
        u1 = 1e-10
    }

    return sqrt(-2.0 * kotlin.math.ln(u1)) *
        kotlin.math.cos(2.0 * Math.PI * u2)
}
