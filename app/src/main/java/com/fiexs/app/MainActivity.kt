package com.fiexs.app

import android.os.Bundle
import androidx.activity.ComponentActivity
import androidx.activity.compose.setContent
import androidx.compose.foundation.Canvas
import androidx.compose.foundation.background
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import kotlinx.coroutines.Job
import kotlinx.coroutines.delay
import kotlinx.coroutines.launch
import kotlin.random.Random

class MainActivity : ComponentActivity() {

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)

        setContent {
            FiexsApp()
        }
    }
}

private val Background = Color(0xFF101114)
private val SurfaceColor = Color(0xFF1B1A20)
private val Accent = Color(0xFFB69CFF)
private val TextColor = Color(0xFFF4F1F8)
private val Muted = Color(0xFF9995A3)

@Composable
fun FiexsApp() {

    var prompt by remember {
        mutableStateOf("")
    }

    var progress by remember {
        mutableIntStateOf(0)
    }

    var isGenerating by remember {
        mutableStateOf(false)
    }

    var generated by remember {
        mutableStateOf(false)
    }

    val gridSize = 32

    var pixels by remember {
        mutableStateOf(
            List(gridSize * gridSize) {
                Background
            }
        )
    }

    val scope = rememberCoroutineScope()

    var generationJob by remember {
        mutableStateOf<Job?>(null)
    }

    MaterialTheme {

        Surface(
            modifier = Modifier.fillMaxSize(),
            color = Background
        ) {

            Column(
                modifier = Modifier
                    .fillMaxSize()
                    .padding(22.dp),

                horizontalAlignment = Alignment.CenterHorizontally
            ) {

                Spacer(modifier = Modifier.height(24.dp))

                Text(
                    text = "FIEXS",
                    fontSize = 34.sp,
                    fontWeight = FontWeight.Black,
                    color = TextColor
                )

                Spacer(modifier = Modifier.height(6.dp))

                Text(
                    text = "PIXEL INTELLIGENCE",
                    fontSize = 11.sp,
                    letterSpacing = 3.sp,
                    color = Accent
                )

                Spacer(modifier = Modifier.height(36.dp))

                Text(
                    text = "Create something.",
                    fontSize = 25.sp,
                    fontWeight = FontWeight.Bold,
                    color = TextColor
                )

                Spacer(modifier = Modifier.height(8.dp))

                Text(
                    text = "Turn your imagination into pixels.",
                    color = Muted,
                    fontSize = 14.sp
                )

                Spacer(modifier = Modifier.height(26.dp))

                OutlinedTextField(
                    value = prompt,

                    onValueChange = {
                        prompt = it
                    },

                    modifier = Modifier.fillMaxWidth(),

                    label = {
                        Text("What do you want to create?")
                    },

                    placeholder = {
                        Text("A rose, a hand, a cat...")
                    },

                    shape = RoundedCornerShape(16.dp),

                    colors = OutlinedTextFieldDefaults.colors(
                        focusedTextColor = TextColor,
                        unfocusedTextColor = TextColor,
                        focusedBorderColor = Accent,
                        unfocusedBorderColor = Color.DarkGray,
                        focusedLabelColor = Accent,
                        cursorColor = Accent
                    ),

                    singleLine = true
                )

                Spacer(modifier = Modifier.height(18.dp))

                Button(
                    onClick = {

                        if (prompt.isBlank()) {
                            return@Button
                        }

                        generationJob?.cancel()

                        generationJob = scope.launch {

                            isGenerating = true
                            generated = false
                            progress = 0

                            val target =
                                createPixelArt(prompt, gridSize)

                            pixels = List(gridSize * gridSize) {
                                Background
                            }

                            val total =
                                gridSize * gridSize

                            for (i in 0 until total) {

                                pixels = pixels.toMutableList()
                                    .also {
                                        it[i] = target[i]
                                    }

                                progress =
                                    ((i + 1) * 100) / total

                                delay(2)
                            }

                            isGenerating = false
                            generated = true
                        }
                    },

                    modifier = Modifier
                        .fillMaxWidth()
                        .height(54.dp),

                    enabled = prompt.isNotBlank()
                            && !isGenerating,

                    shape = RoundedCornerShape(16.dp),

                    colors = ButtonDefaults.buttonColors(
                        containerColor = Accent,
                        contentColor = Color.Black
                    )
                ) {

                    Text(
                        text = if (isGenerating)
                            "Generating..."
                        else
                            "Generate",

                        fontWeight = FontWeight.Bold
                    )
                }

                Spacer(modifier = Modifier.height(28.dp))

                Box(
                    modifier = Modifier
                        .fillMaxWidth()
                        .aspectRatio(1f)
                        .background(
                            SurfaceColor,
                            RoundedCornerShape(20.dp)
                        )
                        .padding(16.dp),

                    contentAlignment = Alignment.Center
                ) {

                    Canvas(
                        modifier = Modifier.fillMaxSize()
                    ) {

                        val cellWidth =
                            size.width / gridSize

                        val cellHeight =
                            size.height / gridSize

                        for (y in 0 until gridSize) {

                            for (x in 0 until gridSize) {

                                val index =
                                    y * gridSize + x

                                drawRect(
                                    color = pixels[index],

                                    topLeft = Offset(
                                        x * cellWidth,
                                        y * cellHeight
                                    ),

                                    size = androidx.compose.ui.geometry.Size(
                                        cellWidth,
                                        cellHeight
                                    )
                                )
                            }
                        }
                    }
                }

                Spacer(modifier = Modifier.height(20.dp))

                if (isGenerating || generated) {

                    Text(
                        text = if (isGenerating)
                            "Creating pixels: $progress%"
                        else
                            "Generation complete",

                        color = Accent,
                        fontSize = 14.sp
                    )

                    Spacer(modifier = Modifier.height(12.dp))

                    LinearProgressIndicator(
                        progress = {
                            progress / 100f
                        },

                        modifier = Modifier.fillMaxWidth(),

                        color = Accent,

                        trackColor = SurfaceColor
                    )
                }

                Spacer(modifier = Modifier.weight(1f))

                Text(
                    text = "FIEXS • OFFLINE PIXEL ENGINE",

                    color = Muted,
                    fontSize = 10.sp,
                    letterSpacing = 1.5.sp
                )

                Spacer(modifier = Modifier.height(12.dp))
            }
        }
    }
}

private fun createPixelArt(
    prompt: String,
    size: Int
): List<Color> {

    val random = Random(prompt.hashCode())

    val pixels = MutableList(size * size) {
        Color(0xFF15151A)
    }

    val normalized =
        prompt.lowercase()

    val isFlower =
        normalized.contains("gül") ||
        normalized.contains("rose") ||
        normalized.contains("flower")

    val centerX = size / 2
    val centerY = size / 2

    for (y in 0 until size) {

        for (x in 0 until size) {

            val index = y * size + x

            val noise = random.nextFloat()

            if (isFlower) {

                val dx = x - centerX
                val dy = y - centerY

                val distance =
                    kotlin.math.sqrt(
                        (dx * dx + dy * dy).toFloat()
                    )

                // Flower petals
                if (distance < 10 &&
                    distance > 3
                ) {

                    pixels[index] =
                        when {

                            noise > 0.8f ->
                                Color(0xFFFF8BA8)

                            noise > 0.4f ->
                                Color(0xFFE94F78)

                            else ->
                                Color(0xFFB51F50)
                        }
                }

                // Flower center
                if (distance <= 3) {

                    pixels[index] =
                        Color(0xFFFFD76E)
                }

                // Stem
                if (
                    x in (centerX - 1)..(centerX + 1) &&
                    y > centerY + 7 &&
                    y < size - 4
                ) {

                    pixels[index] =
                        Color(0xFF3B9B58)
                }

                // Leaves
                if (
                    y in (centerY + 10)..(centerY + 16) &&
                    (
                        x in (centerX - 7)..(centerX - 3) ||
                        x in (centerX + 3)..(centerX + 7)
                    )
                ) {

                    pixels[index] =
                        Color(0xFF64C878)
                }

            } else {

                // Generic pixel art prototype

                val dx = x - centerX
                val dy = y - centerY

                val inside =
                    kotlin.math.abs(dx) < 10 &&
                    kotlin.math.abs(dy) < 10

                if (inside) {

                    pixels[index] =
                        when (random.nextInt(4)) {

                            0 -> Color(0xFFB69CFF)

                            1 -> Color(0xFF8C73D8)

                            2 -> Color(0xFF6650A4)

                            else -> Color(0xFFD6C8FF)
                        }
                }

                // Decorative pixels
                if (
                    random.nextFloat() > 0.985f
                ) {

                    pixels[index] =
                        Color(0xFFB69CFF)
                }
            }
        }
    }

    return pixels
}